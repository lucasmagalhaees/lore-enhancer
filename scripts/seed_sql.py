"""Writes sql/seed.sql from corpus/*.json: one paste in the Supabase SQL Editor loads (or tops up) the whole corpus."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
q = lambda v: 'null' if v is None else "'" + str(v).replace("'", "''") + "'"
F = json.load(open(ROOT / 'corpus/fragments.json')); T = json.load(open(ROOT / 'corpus/templates.json'))
out = ['-- generated by scripts/seed_sql.py from corpus/: do not edit by hand', 'begin;']
out.append('insert into fragment (campaign, area, god, moment, kind, text, source, source_date) values')
out.append(',\n'.join(f"({q(f['campaign'])}, {q(f['area'])}, {q(f['god'])}, {q(f['moment'])}, {q(f['kind'])}, {q(f['text'])}, {q(f['source'])}, {q(f['source_date'])})" for f in F))
out.append('on conflict (campaign, kind, text) do nothing;')
out.append('insert into template (campaign, moment, text) values')
out.append(',\n'.join(f"({q(t['campaign'])}, {q(t['moment'])}, {q(t['text'])})" for t in T))
out.append('on conflict (campaign, moment, text) do nothing;')
out.append('commit;')
(ROOT / 'sql/seed.sql').write_text('\n'.join(out) + '\n')
print(f'sql/seed.sql: {len(F)} fragmentos, {len(T)} moldes')
